/* Всё, что ПЛИС делает для машины помимо привода: выключатели устройств, ВГ93,
 * VGA, ВИ53, клавиши ВВОД и СБР, подставной загрузчик, диагностика новых узлов.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ ata.c. Там привод и шина IDE; здесь настройки и узлы,
 * которые от привода не зависят и есть не в каждом битстриме. Какие есть,
 * ПЛИС говорит сама: байт 0x6F -- набор узлов, 0x6E -- версия раскладки
 * (конец hdl/top.v). Старый битстрим на эти коды отвечает состоянием, и
 * board_probe это отличает.
 *
 * НАСТРОЙКИ ЖИВУТ В ПЛИС ДО ПЕРВОГО СБРОСА ПО ПИТАНИЮ. Включение и перезаливка
 * возвращают их к умолчаниям (hdl/ide_remote.v, блок por), поэтому прошивка
 * хранит их у себя и заливает обратно: при старте, когда ПЛИС ожила после
 * молчания, и после сеанса XVC. */
#ifndef COMBO_BOARD_H
#define COMBO_BOARD_H

#include <stddef.h>
#include <stdint.h>

/* Набор узлов битстрима, байт 0x6F. */
#define BF_FDC    0x01
#define BF_VI53   0x02
#define BF_MOUSE  0x04
#define BF_KEYS   0x08
#define BF_LOADER 0x10
#define BF_MIRROR 0x20
#define BF_WATCH  0x40
#define BF_VIDEO  0x80
/* Байт 0x6E, младшие разряды. */
#define BF2_AY          0x01
#define BF2_KVAZ2       0x02
#define BF2_AUDIO_SPLIT 0x04
#define BF2_KBD         0x08    /* сброс с клавиатуры различается, есть C_BOOT и блок 6 */

/* Разряды маски выключенных устройств, C_DEV. */
#define DEV_FDC    0x01
#define DEV_KVAZ1  0x02
#define DEV_KVAZ2  0x04
#define DEV_IDE    0x08
#define DEV_AY     0x10
#define DEV_MIRROR 0x20
#define DEV_MASK   0x3F

typedef struct {
    uint8_t dev_off;    /* DEV_*: 1 -- устройство не отвечает на шине */
    uint8_t fdc_rdy;    /* готовность ВГ93: 0 контакт 34, 1 по индексу, 2 всегда */
    uint8_t fdc_pc;     /* предкомпенсация: 3..0 шаги по 62,5 нс, 4 -- с 44-й дорожки */
    uint8_t vga60;      /* 1 -- VGA 60 Гц 720x900 (по умолчанию), 2 -- 60 Гц 640x1024 (5:4,
                           rev5), 0 -- 50 Гц с привязкой к машине (rev5 -- 5:4 для
                           перешитых мониторов, rev4 -- 576p) */
    uint8_t vi53_off;   /* 1 -- эмуляция ВИ53 выключена, звук даёт сама машина */
    uint8_t boot;       /* BOOT_*: чем грузится машина */
    uint8_t fdd_cable;  /* шлейф дисковода: 0 Шугарт (A: 10, B: 12, мотор 16),
                           1 ПК с перекруткой (A: 12, B: 16, мотор 10),
                           2 Шугарт, A:/B: переставлены (A: 12, B: 10, мотор 16) --
                           под 3,5" с DS1 намертво (SFD-321B), hdl/top.v */
    uint8_t autostart;  /* 1 -- автозапуск загруженного: на мигании РУС/ЛАТ в конце
                           загрузки (BOOT26 или ПЗУ) плата сама жмёт СБР
                           (hdl/fakerom.v); от boot не зависит */
} board_settings_t;

/* Чем грузится машина. Настройка живёт в прошивке: при включении ESP сама
 * решает, отпустить ли ВВОД (загрузка из ПЗУ) или нажать СБР с подставным
 * загрузчиком. В ПЛИС уходит только последнее (C_BOOT). */
#define BOOT_ROM    0       /* как без платы: загрузчик из ПЗУ */
#define BOOT_POWER  1       /* при включении -- подставной загрузчик */
#define BOOT_VVOD   2       /* и после каждого ВВОД с клавиатуры тоже */

/* Как в ПЛИС по сбросу. Тогда плата без сохранённых настроек ведёт себя ровно
 * так же, как до этой прошивки. VGA по умолчанию -- 60 Гц (23.10.2026):
 * 800x600@50 не стандарт, мониторы его не берут (HP L1908w на первой rev4 --
 * «Out of Range»). Сохранённая запись любой версии несёт vga60 сама, выбор
 * хозяина при обновлении не трогается. */
#define BOARD_SETTINGS_DEFAULT { 0, 1, 0, 1, 0, BOOT_ROM, 0, 1 }

int  board_settings_valid(const board_settings_t *s);

/* Прочитать набор узлов. 0 -- битстрим знает блоки 4 и 5, иначе -1 (старый
 * битстрим, ПЛИС не загружена, обрыв SPI). */
int     board_probe(void);
int     board_present(void);        /* последний board_probe удался */
uint8_t board_features(void);       /* BF_*, ноль без board_present */
uint8_t board_features2(void);      /* BF2_* */
int     board_rev5(void);           /* битстрим rev5: джойстики, ВГ93 у ESP, винт в ПЛИС */

/* Загрузить сохранённое, опознать ПЛИС и залить настройки. Звать один раз,
 * после link_open. */
void board_init(void);

/* Текущие настройки (то, что прошивка считает залитым). */
void board_get(board_settings_t *out);

/* Залить в ПЛИС и сохранить. -1 -- значения вне диапазона, ничего не
 * менялось. */
int  board_set(const board_settings_t *s);

/* Залить ещё раз то, что есть, -- после перезаливки ПЛИС. */
void board_reapply(void);

/* Сохранение: NVS на плате, память на маке. */
int  board_settings_load(board_settings_t *out);   /* 0 -- было сохранено */
int  board_settings_save(const board_settings_t *s);

/* Клавиши машины. -1 -- в битстриме нет автозапуска. */
#define KEY_RELEASE 0       /* отпустить всё сейчас же */
#define KEY_VVOD    1       /* ВВОД на 50 мс: перезагрузка из ПЗУ */
#define KEY_SBR     2       /* СБР на 50 мс: загрузка с отключённым ПЗУ */
int  board_keys(int what);

/* Нажат ли ВВОД прямо сейчас. С включения ПЛИС держит его 2 с сама. */
int  board_vvod_held(void);

/* Продлить удержание ВВОДа ещё на 2 с -- ТОЛЬКО если он уже нажат. Команда 3
 * на отпущенной клавише сама нажала бы ВВОД и перезагрузила работающую
 * машину (hdl/autostart.v), поэтому проверка здесь, а не у вызывающего.
 * 1 -- продлено, 0 -- не нажат, -1 -- автозапуска нет. */
int  board_vvod_extend(void);

/* Подставной загрузчик. -1 -- в битстриме его нет. */
#define LOADER_OFF  0
#define LOADER_ARM  1       /* взвести: окно откроется по нашему СБР */
#define LOADER_BOOT 2       /* взвести и нажать СБР */
int  board_loader(int what);

/* Отпустить машину, которую ПЛИС держит ВВОДОМ с включения: при BOOT_ROM --
 * отпустить ВВОД, и машина грузится из ПЗУ; иначе -- взвести загрузчик и
 * нажать СБР (ВВОД autostart.v отпустит сам, через паузу между клавишами).
 * Нет загрузчика в битстриме -- тоже из ПЗУ. 1 -- нажат СБР, 0 -- отпущен
 * ВВОД, -1 -- клавиш нет. */
int  board_release(void);

/* rev5. Квазидиск заново после ВВОД с клавиатуры: разряд 2 C_BOOT, ПЛИС держит
 * узнанный ВВОД, пока ESP льёт образ (hdd_esp.c). */
void board_boot_kd(int on);
/* Виртуальный дисковод (vfd_esp.c) вместо A: (1) или B: (2), 0 -- нет:
 * разряды 4..3 команды 4Ah. */
void board_set_vfd(int letter);
/* Отпустить машину после такого ВВОД: BOOT26 при BOOT_VVOD, иначе ПЗУ. */
int  board_release_vvod(void);

/* Снимок экрана машины: 256 строк картинки по 128 байт -- слой 0 (8000h)
 * колонки 0..31, слой 1, 2, 3; в байте левая точка -- старший разряд. Строка y
 * -- уже с прокруткой, как на экране. Цвета -- отдельно, board_palette. 0 --
 * снято, -1 -- нет генератора кадра, -2 -- строка не пришла (выборка стоит).
 * Занимает шину SPI на ~150 мс. */
#define SCR_ROWS      256
#define SCR_ROW_BYTES 128
int  board_screen(uint8_t *frame);

/* rev5: СНИМОК КАДРА ИЗ PSRAM (doc/NEXT.md 16.2). ПЛИС снимает каждую строку
 * под лучом в PSRAM, по чётности кадра (hdl/fb_snap.v), и в блоке 6 отдаёт
 * подпись SNAP_SIGN (байт 6) и чётность последнего снятого кадра (байт 0,
 * разряд 0). Тогда board_screen берёт кадр оттуда целиком: строки одного
 * кадра «Вектора», а не склейку из нескольких, и быстрее -- 65 блоков по 512
 * байт. Читает board_ps_fn: окно на PSRAM как есть (указатель с разрядом 20,
 * hdl/esp_mem.v), блоки по списку, буферы ПЛИС -- конвейером, под замком
 * hdd_esp.c. */
#define SNAP_SIGN      0xC5                       /* байт 6 блока 6 */
#define SNAP_XRAW      0x180000u                  /* окно: PSRAM 80000h как есть */
#define SNAP_PAR       0x10000u                   /* снимок чётности 1 */
#define SNAP_MAP       0x8000u                    /* карта: строка экрана -> строка памяти */
extern int (*board_ps_fn)(const uint32_t *xaddr, int n, uint8_t *dst);
int  board_snap_present(void);

/* ИЗМЕНЁННЫЕ СТРОКИ (doc/NEXT.md 16.3). Рядом с картой ПЛИС пишет отметки
 * (SNAP_FLAGS + y, разряд 0: строку памяти под строкой экрана y снимали
 * заново), в блоке 6 -- номер снятого целиком кадра (байт 1), его чётность
 * (байт 0, разряд 1) и «терялось задание» (разряд 2). board_snap_track
 * берёт карту и отметки каждого кадра и ведёт для строки памяти r номер кадра
 * (свой, 32 разряда), где она последний раз изменилась или снова
 * показалась; пропуск кадра -- изменилось всё. Кадр по карте собирает
 * браузер: прокрутка строк не тащит.
 *
 * board_screen_delta -- строки, изменённые после кадра since (0 -- все
 * показанные), из свежего снимка:
 *   0..3   "VDL1"
 *   4      разряд 0 -- здесь все показанные строки (браузер чистит своё)
 *   8..11  номер кадра (since для следующего запроса), младший байт первым
 *   12     карта: 256 байт, строка экрана -> строка памяти
 *   268    32 байта: строки памяти в ответе, разряд r mod 8 байта r / 8
 *   300    строки по возрастанию r, по 128 байт: слой 0..3 x колонка 0..31
 * Длина -- в *len. 0 -- готово, -1 -- снимка в PSRAM нет, -2 -- кадр не
 * пришёл или снимок переписали, пока читали. */
#define SNAP_FLAGS     0x8100u                    /* отметки: 256 байт за картой */
#define SCR_DELTA_HDR  300
#define SCR_DELTA_MAX  (SCR_DELTA_HDR + SCR_ROWS * SCR_ROW_BYTES)
int  board_screen_delta(uint8_t *out, uint32_t since, size_t *len);
/* шаг слежения: 1 -- взят новый кадр, 0 -- нового нет, < 0 -- сбой связи */
int  board_snap_track(void);
/* миллисекунды link_ms последнего board_screen_delta: следить, пока смотрят */
uint32_t board_snap_used(void);
/* замок шины SPI (hdd_esp.c): слежение и чтение кадра -- под ним */
extern void (*board_ps_lock)(int on);

/* Палитра машины: 16 байт BBGGGRRR, ячейка -- номер цвета точки; 17-й байт --
 * порт B: разряд 4 -- режим 512 точек, 3..0 -- бордюр. Это палитра и режим,
 * какими их ведёт ПЛИС по записям в порты вне картинки; смены под лучом
 * (мультиколор) на снимок не попадают. 0 -- прочитана, -1 -- битстрим её не
 * отдаёт. */
#define SCR_PAL_BYTES 17
#define SCR_PB_512    0x10
int  board_palette(uint8_t pal[SCR_PAL_BYTES]);

/* Журнал записей машины в порты палитры и порта B -- диагностика, разбор в
 * hdl/vid_rec.v («журнал записей»): 2048 байт как их отдаёт ПЛИС. 0 --
 * прочитан, -1 -- битстрим палитру не отдаёт. Старый битстрим журнала не
 * ведёт: за 17-м байтом там по кругу повторяется палитра. */
/* Бордюр по строкам растра 0..311: цвет BBGGGRRR на начало строки, как его
 * кладёт ПЛИС в статику (hdl/fb_copy.v, «БОРДЮР»), и 313-й байт -- номер
 * кадра машины 0..63, который сейчас идёт (hdl/snd_tap.v). Читать статику
 * умеет только плата с переносом блока (rev5): board_sram_fn ставит
 * hdd_esp.c и берёт буферы ПЛИС под своим замком. 0 -- прочитан, -1 -- нечем. */
#define SCR_BORDER_LINES 312
#define SCR_FRAMES       64                 /* кольцо звука, кадров */
extern int (*board_sram_fn)(uint32_t xaddr, uint8_t *dst, int len);
int  board_border(uint8_t b[SCR_BORDER_LINES + 1]);

/* Звук кадра машины k (0..63): по строке растра 0..311 -- левый и правый,
 * 0..200 (hdl/snd_tap.v). Кадр готов, когда номер кадра уже ушёл дальше. */
#define SND_FRAME_BYTES  (SCR_BORDER_LINES * 2)
int  board_snd_frame(int k, uint8_t out[SND_FRAME_BYTES]);

#define PAL_LOG_BYTES 2048
int  board_pal_log(uint8_t buf[PAL_LOG_BYTES]);

/* ТЕКСТОВЫЙ РЕЖИМ 80x25 (doc/TEXT.md). Битстрим rev5 с ним отдаёт в блоке
 * диагностики 6 состояние режима, байт 7 -- подпись A5h. Шрифт (fw/font866.c)
 * ПЛИС берёт из статики, а заливает его туда ESP: board_sram_wr_fn ставит
 * hdd_esp.c, как board_sram_fn. */
#define TXT_COLS      80
#define TXT_ROWS      25
#define TXT_BYTES     (TXT_COLS * TXT_ROWS * 2)   /* знак и цвет на знакоместо */
#define TXT_HDR       8                           /* блок 6 как есть */
#define TXT_SIGN      0xA5                        /* байт 7 блока 6 */
#define TXT_FONT_XADDR 0xA1000u                   /* DD6B, страница 2, 1000h */
/* Байт 0 блока 6 -- регистр режима. */
#define TXT_ON        0x01
#define TXT_CURSOR    0x02
#define TXT_BLINK     0x04
extern int (*board_sram_wr_fn)(uint32_t xaddr, const uint8_t *src, int len);
int  board_text_present(void);     /* битстрим знает текстовый режим */
/* Залить шрифт в статику. 0 -- залит, -1 -- режима нет или нечем писать.
 * Зовут hdd_esp.c (когда поставил board_sram_wr_fn) и board_reapply. */
int  board_text_font(void);
/* Текстовый экран: out[0..7] -- блок 6, out[8..] -- 4000 байт экрана из
 * зеркала ОЗУ с адреса экрана, строки в порядке буфера (верхняя строка --
 * в out[3], поворачивает показ). Как board_screen, ждёт начала кадра машины.
 * 1 -- экран прочитан, 0 -- режим выключен (out не заполнен), -1 --
 * режима нет в битстриме или нечем читать, -2 -- чтение не вышло. */
int  board_text(uint8_t out[TXT_HDR + TXT_BYTES]);

/* Блоки диагностики 4 и 5 как есть, по восемь байт. */
void board_diag(uint8_t d4[8], uint8_t d5[8]);
/* Блок 6; без BF2_KBD -- нули. */
void board_diag6(uint8_t d6[8]);

/* Разобранная диагностика и настройки -- JSON для /api/board. Возвращает
 * длину, как snprintf. */
int  board_json(char *out, int max);

/* Шаг фоновых дел: замечает, что ПЛИС ожила после молчания (перезаливка), и
 * заливает настройки. Звать из цикла обслуживания, дёшево. */
void board_tick(void);

/* Попросить залить настройки на ближайшем шаге: после сеанса XVC. Можно
 * звать из другой задачи. */
void board_reapply_later(void);

#endif
