/* Проигрыватель PCM rev5: ESP раскладывает файл в отсчёты и кладёт их в кольцо
 * в статике, ПЛИС играет (hdl/pcm.v, doc/IDEAS.md «Проигрыватель PCM и MP3»).
 *
 * Здесь всё, что не зависит от платы: почта «Вектора», кольцо, пересчёт
 * частоты, громкость, плавные вход и выход. С платой говорит через pcm_ops_t,
 * с файлом -- через pcm_src_t, так что на маке это гоняется против подставной
 * ПЛИС (fw/test_pcm.c).
 *
 * ПОЧТА «ВЕКТОРА» (порт 3Ch, запись -- один байт; режим игры -- ниже):
 *   00h        стоп (с плавным выходом)
 *   01h..7Fh   играть дорожку N один раз
 *   80h        длинная команда: дальше два байта -- адрес блока параметров
 *              в ОЗУ «Вектора», младший и старший
 *   81h..FEh   играть дорожку N - 80h по кругу
 *   FFh        ничего (пинок сторожа режима игры; до 13.11.2026 -- дорожка 127
 *              по кругу)
 * Дорожка N -- N-й по алфавиту файл в папке music на карте (как дискеты
 * у Gotek с FlashFloppy: имена любые). Следующий байт -- только когда
 * разряд 0 состояния погас: два подряд сольются в последний.
 *
 * ДЛИННЫЕ КОМАНДЫ -- музыка, которую игра везёт с собой. Игра читает файл со
 * своего диска в буфер в ОЗУ и отдаёт его кусками в ячейку проигрывателя; ESP
 * берёт байты из зеркала ОЗУ (DD6B, страница 0: туда ложится каждая запись
 * процессора в ОЗУ). Буфер и блок -- в ОЗУ машины, не в окне квазидиска, и
 * зеркало должно быть включено (оно включено по умолчанию). Блок параметров
 * (слова -- младшим байтом вперёд):
 *   01h, n                 начать ячейку n (1..63): прежнее содержимое долой;
 *                          ячейка растёт кусками
 *   02h, n, адрес, длина   дописать в ячейку n столько байт с адреса (до 64 КБ,
 *                          без перехода через FFFFh). Играющую ячейку WAV или
 *                          MP3 дозапись не останавливает
 *   03h, n, флаги          играть ячейку n музыкой; флаги, разряд 0 -- по кругу
 *   04h, v                 громкость музыки 0..16 (16 -- как в файле)
 *   05h, n                 освободить ячейку n, 0 -- все
 *   06h, n, адрес          таблица эффектов: n записей (0..127) по 4 байта с
 *                          адреса: ячейка, повторов (1..255), частота в Гц
 *                          (слово, 4000..22050). Эффект N -- запись N
 *   07h, m                 режим игры: 1 -- включить, 0 -- выключить
 *   08h, что               стоп: разряд 0 -- музыка, разряд 1 -- эффект
 *   09h, v                 громкость эффектов 0..16
 *   0Ah, n, длина(3)       начать ячейку n, зная длину: память берётся сразу
 *                          на всю, и ячейку можно играть, пока её дописывают
 *                          (01h этого не может: у старых программ в байтах
 *                          2..4 блока -- остатки прошлой команды)
 *   0Bh, t                 сторож режима игры: t десятых секунды (1..255),
 *                          0 -- как по умолчанию, 2 с
 * Формат музыкальной ячейки ESP узнаёт сам: WAV, MOD или MP3. Ячейка эффекта
 * -- сырые отсчёты: 8 бит со знаком, моно (.SND Gobliiins). Все ячейки вместе
 * -- не больше PCM_MEM_MAX. Команда исполнена, когда переключился разряд 4
 * состояния; после этого буфер можно занимать, а разряд 2 говорит, удалась ли
 * она. Дописываемую ячейку можно пускать, когда в ней заголовок WAV или первые
 * 4 КБ MP3; MOD -- только целую.
 *
 * РЕЖИМ ИГРЫ (07h, 1) -- музыка и эффекты сразу (doc/PCM-GAME.md). Почта
 * становится такой:
 *   00h        стоп эффекта (музыка играет)
 *   01h..7Fh   эффект N из таблицы (06h): обрывает прежний эффект, музыку не
 *              трогает. Звучит через 6-14 мс после OUT -- ждать разряда 0 не
 *              надо, его можно слать прямо из прерывания
 *   80h        длинная команда, как всегда
 *   81h..FEh   не значат ничего (ошибка)
 *   FFh        пинок сторожа, больше ничего
 * СТОРОЖ: в режиме игры почта (любая, в том числе FFh) должна приходить чаще,
 * чем раз в 2 с (0Bh -- другой срок). Нет почты -- игра повисла или «Вектор»
 * сброшен: музыка и эффект гаснут, режим игры выключается, и до 07h
 * короткая почта, кроме FFh, не значит ничего (ошибка). Пинать удобно из
 * прерывания, только когда разряд 0 состояния погас: иначе пинок затрёт
 * эффект, ещё не забранный ESP (а сам эффект -- тоже пинок).
 * Музыка в режиме игры держит впереди не 2,8 с, а PCM_GAME_AHEAD блоков: ESP
 * подмешивает эффект в уже записанные блоки, и их должно быть мало. Включать
 * режим лучше до музыки: блоки, записанные раньше, ESP не перепишет, и до 2,8 с
 * эффекты будут звучать позже. Выход идёт без перерыва и на середине (80h),
 * пока режим включён, даже без музыки. Старая прошивка (до 13.11.2026) на 06h
 * и 07h отвечает ошибкой: так игра узнаёт, что второго голоса нет.
 * Петля MP3 без зазора -- если в файле заголовок LAME: его пишет lame в VBR
 * (lame -V 9 -m m), в CBR на 22 кГц не пишет (кадр мал).
 *
 * СОСТОЯНИЕ ДЛЯ «ВЕКТОРА» (чтение порта 3Ch):
 *   разряд 0   команда ещё не забрана (ставит ПЛИС)
 *   разряд 1   играет
 *   разряд 2   последняя команда не исполнена: нет дорожки или ячейки, файл не
 *              читается, не хватило памяти
 *   разряд 3   проигрыватель есть (ESP жива и его завела)
 *   разряд 4   переключается, когда исполнена длинная команда
 *   разряд 5   звучит эффект (только в режиме игры)
 *   7..6       нули: не нули -- проигрывателя нет. До режима игры нулём
 *              бывает и разряд 5: проверять проигрыватель -- до 07h
 * В режиме игры разряд 1 -- играет музыка (выход работает всегда).
 */
#ifndef COMBO_PCM_PLAY_H
#define COMBO_PCM_PLAY_H

#include <stdint.h>

#define PCM_RATE      44092             /* 50 МГц / 1134 (hdl/pcm.v, DIV) */
#define PCM_BLK       512               /* байт в блоке кольца */
#define PCM_NBLK      512               /* блоков в кольце */
#define PCM_AHEAD     480               /* сколько блоков держать впереди */
#define PCM_GAME_AHEAD 8                /* то же в режиме игры, 46 мс */
#define PCM_FX_LEAD   2                 /* эффект -- с блока rp + 2: 6-12 мс */

#define PCM_ST_PLAY   0x02
#define PCM_ST_ERR    0x04
#define PCM_ST_READY  0x08
#define PCM_ST_SEQ    0x10
#define PCM_ST_FX     0x20

#define PCM_SLOTS     64                /* ячейки 1..63 */
#define PCM_FX_MAX    127               /* эффектов в таблице */
#define PCM_MEM_MAX   (1024L * 1024)    /* все ячейки вместе, байт (PSRAM) */
enum { PCM_OP_BEGIN = 1, PCM_OP_APPEND, PCM_OP_PLAY, PCM_OP_VOLUME, PCM_OP_FREE,
       PCM_OP_FX_TABLE, PCM_OP_GAME, PCM_OP_STOP, PCM_OP_FX_VOLUME, PCM_OP_BEGIN_SIZE,
       PCM_OP_WATCHDOG };

#define PCM_SRC_WAIT  (-2)              /* read: в ячейке пока нет, но будет */

/* Источник: файл, разложенный в 16-разрядные отсчёты. */
typedef struct pcm_src {
    int   rate;                         /* отсчётов в секунду */
    int   ch;                           /* 1 или 2 */
    /* до n кадров (по ch отсчётов) в dst; 0 -- конец, <0 -- ошибка */
    int  (*read)(struct pcm_src *s, int16_t *dst, int n);
    int  (*rewind)(struct pcm_src *s);  /* в начало, для игры по кругу */
    void (*close)(struct pcm_src *s);
    void *st;
    int   fixed;                        /* держит адрес ячейки: realloc её убьёт (MOD) */
} pcm_src_t;

typedef struct {
    /* обмен с ПЛИС: C_PCM (combo_pcm); 0 -- проигрыватель отвечает */
    int (*xchg)(void *ctx, uint8_t ctl, uint16_t lim, uint16_t *rp, int *mail);
    /* блок кольца b (0..511) -- 512 байт */
    int (*ring_write)(void *ctx, int b, const uint8_t *data);
    /* открыть дорожку n (1..127); 0 -- открыта */
    int (*open)(void *ctx, int n, pcm_src_t *src);
    /* источник из ячейки: *d и *have живут, пока источник открыт; size --
     * сколько будет всего, 0 -- сколько есть (pcm_src_open_mem) */
    int (*open_mem)(void *ctx, uint8_t *const *d, const long *have, long size, pcm_src_t *src);
    /* n байт ОЗУ «Вектора» с адреса a (зеркало в статике); 0 -- прочитано */
    int (*mem_read)(void *ctx, uint16_t a, uint8_t *dst, int n);
    void *ctx;
} pcm_ops_t;

void pcm_init(const pcm_ops_t *ops);
/* Шаг: обмен с ПЛИС, почта, долив кольца (не больше max блоков за раз).
 * Вызывать каждые несколько миллисекунд. 1 -- играет, 0 -- молчит,
 * 2 -- идёт обмен почтой (длинная команда, загрузка) или включён режим игры:
 * звать раз в миллисекунду; -1 -- ПЛИС не ответила. */
int  pcm_tick(int max);
/* То же, что байт из почты (00h, N, 80h + N, длинная) -- для морды и стендов. */
void pcm_command(int cmd);
void pcm_volume(int v);                 /* 0..16, 16 -- как в файле */
uint8_t pcm_state(void);                /* PCM_ST_* */
/* Недоборов с запуска: ПЛИС дошла до границы, пока звук шёл (ESP не успела). */
unsigned long pcm_underruns(void);
/* Сколько раз сработал сторож режима игры. */
unsigned long pcm_watchdog_fired(void);

#endif
